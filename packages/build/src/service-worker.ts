import type { AssetMetadata } from './types.js';

/** Exact pre-application names shared with forma-server's retiring worker. */
export const V1_CACHE_NAMES = /^forma-(?:dev|[0-9a-f]{12})(?:-on-demand-v1)?$/;
export const APP_NAME = /^[a-z0-9][a-z0-9-]{0,62}$/;

/** The cache a per-application worker writes: `forma:<app>:<build>`. */
export function appCacheName(app: string, buildHash: string): string {
  return `forma:${app}:${buildHash.slice(0, 12)}`;
}

export interface WorkerInput {
  app: string;
  build: string;
  /** Final uncompressed bytes have already been hashed by generateManifest. */
  assets: Readonly<Record<string, AssetMetadata>>;
  development?: boolean;
  /** Assets such as the preview frame runtime are inlined, never fetched. */
  excludedFiles?: readonly string[];
}

/** Exact URLs, independent of hash-like filename spelling. */
export function workerIntegrityTable(input: WorkerInput): Record<string, string> {
  const excluded = new Set(input.excludedFiles);
  const table: Record<string, string> = {};
  for (const file of Object.keys(input.assets).sort()) {
    const metadata = input.assets[file];
    if (metadata.immutable !== true || excluded.has(file) || file === 'sw.js' || !/\.(?:js|css|wasm)$/.test(file)) continue;
    if (!file || file.startsWith('/') || /[\\?#:\u0000-\u001f\u007f]/.test(file)
        || file.split('/').some(part => !part || part === '.' || part === '..')) {
      throw new Error(`BUILD-818 worker asset has an unsafe filename: ${JSON.stringify(file)}`);
    }
    if (!/^sha384-[A-Za-z0-9+/]{64}$/.test(metadata.integrity)) {
      throw new Error(`BUILD-818 worker asset ${file} needs its full canonical SHA-384 integrity`);
    }
    table[`/_assets/${file.split('/').map(encodeURIComponent).join('/')}`] = metadata.integrity;
  }
  return table;
}

/** Production: no install fetches or forced takeover; every protected response
 * is authenticated, even when CacheStorage was populated by another script. */
export function serviceWorkerSource(input: WorkerInput): string {
  if (input.development) return DEVELOPMENT_WORKER;
  if (typeof input.app !== 'string' || !APP_NAME.test(input.app) || typeof input.build !== 'string' || !input.build || input.build.includes(':')) {
    throw new Error('a production worker needs a validated forma:<app>:<build> identity');
  }
  const cacheName = appCacheName(input.app, input.build);
  const integrity = workerIntegrityTable(input);
  return `// Generated by @getforma/build — on-demand immutable assets only, SHA-384 verified
const CACHE_NAME = ${JSON.stringify(cacheName)};
const OWN_PREFIX = ${JSON.stringify(`forma:${input.app}:`)};
const V1_CACHE_NAMES = ${V1_CACHE_NAMES.toString()};
const ASSET_INTEGRITY = new Map(${JSON.stringify(Object.entries(integrity))});

// No install work: an old tab keeps its worker until every old tab closes.
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((names) => Promise.all(names
    .filter((name) => name !== CACHE_NAME && (V1_CACHE_NAMES.test(name) || name.startsWith(OWN_PREFIX)))
    .map((name) => caches.delete(name)))).catch(() => {}));
});

function eligible(response) {
  const control = response.headers.get('Cache-Control') || '';
  const type = response.headers.get('Content-Type') || '';
  return response.status === 200 && !response.redirected
    && !['opaque', 'opaqueredirect', 'error'].includes(response.type)
    && /(?:^|,)\\s*immutable\\s*(?:,|$)/i.test(control)
    && !/(?:^|,)\\s*(?:no-store|private)\\b/i.test(control)
    && /^(?:application\\/(?:javascript|wasm)|text\\/(?:javascript|css))(?:;|$)/i.test(type);
}
async function verified(response, expected) {
  try {
    if (!eligible(response) || !self.crypto || !self.crypto.subtle) return false;
    const bytes = await response.clone().arrayBuffer();
    const digest = await self.crypto.subtle.digest('SHA-384', bytes);
    return 'sha384-' + btoa(String.fromCharCode(...new Uint8Array(digest))) === expected;
  } catch { return false; }
}
self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || request.mode === 'navigate' || request.cache === 'no-store' || request.cache === 'reload'
      || url.origin !== self.location.origin || url.search || !ASSET_INTEGRITY.has(url.pathname)) return;
  const expected = ASSET_INTEGRITY.get(url.pathname);
  event.respondWith((async () => {
    let cache;
    let eviction = Promise.resolve();
    try {
      cache = await caches.open(CACHE_NAME);
      const cached = await cache.match(request);
      if (cached) {
        if (await verified(cached, expected)) return cached;
        // Deletion failure cannot permit bad bytes, or hold a valid network
        // response hostage. A later hit is checked again even if this fails.
        eviction = Promise.resolve().then(() => cache.delete(request)).catch(() => {});
        event.waitUntil(eviction);
      }
    } catch { /* Storage failure still permits a verified network response. */ }
    // A bad HTTP-cache entry must not survive an authenticated refetch.
    const response = await fetch(request, { cache: 'no-store' });
    if (!await verified(response, expected)) throw new TypeError('FORMA_E_SW_INTEGRITY: protected asset verification failed');
    if (cache) {
      const copy = response.clone();
      event.waitUntil(eviction.then(() => cache.put(request, copy)).catch(() => {}));
    }
    return response;
  })());
});
`;
}

const DEVELOPMENT_WORKER = `// Generated by @getforma/build — development assets are network-only
self.addEventListener('install', (event) => {
  event.waitUntil(self.skipWaiting());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(
        names.filter((name) => name.startsWith('forma-')).map((name) => caches.delete(name))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith('/_assets/')) return;
  event.respondWith(fetch(event.request, { cache: 'no-store' }).then((response) => {
    // Servers may advertise long-lived cache headers for /_assets/. Override
    // those too, or the page's subresource cache can skip the worker next time.
    const headers = new Headers(response.headers);
    headers.set('Cache-Control', 'no-store');
    return new Response(response.body, {
      status: response.status,
      statusText: response.statusText,
      headers,
    });
  }));
});
`;