use axum::{
    extract::State,
    http::{header, StatusCode},
    response::{Html, IntoResponse, Response},
    routing::get,
    Router,
};
use forma_ir::{IrModule, SlotData};
use forma_server::{assets, load_ir_modules, render_page, sw, PageConfig, RenderMode};
use rust_embed::Embed;
use std::collections::HashMap;
use std::sync::Arc;

#[derive(Embed)]
#[folder = "admin/dist/"]
struct Assets;

struct AppState {
    manifest: forma_server::AssetManifest,
    /// Per-route render mode, decided at startup by what the frontend build
    /// emitted: `npm run build` produces no `.ir`, so every route stays
    /// Phase 1; `npm run build:ssr` emits one and the route becomes Phase 2.
    render_modes: HashMap<String, RenderMode>,
    ir_modules: HashMap<String, IrModule>,
}

#[tokio::main]
async fn main() {
    // Without a subscriber, forma-server's warnings — including "IR walk
    // failed, falling back to Phase 1" — go nowhere, and a broken SSR build
    // looks exactly like a working Phase 1 one. Keep this.
    tracing_subscriber::fmt::init();

    // Check if frontend has been built
    if Assets::get("manifest.json").is_none() {
        eprintln!("\n  Error: Frontend not built yet.\n");
        eprintln!("  Run these commands first:");
        eprintln!("    cd admin");
        eprintln!("    npm install");
        eprintln!("    npm run build\n");
        std::process::exit(1);
    }

    let manifest = assets::load_manifest::<Assets>();
    let (render_modes, ir_modules) = load_ir_modules::<Assets>(&manifest);

    match render_modes.get("/") {
        Some(RenderMode::Phase2SsrReconcile) => {
            tracing::info!("/ is Phase 2 (server-rendered from IR)");
        }
        _ => {
            tracing::info!(
                "/ is Phase 1 (client mount). Run `npm run build:ssr` in admin/ for Phase 2."
            );
        }
    }

    let state = Arc::new(AppState { manifest, render_modes, ir_modules });

    let app = Router::new()
        .route("/", get(home))
        .route("/favicon.ico", get(favicon))
        .route("/sw.js", get(sw::serve_sw::<Assets>))
        .route("/_assets/{*filename}", get(assets::serve_asset::<Assets>))
        .with_state(state);

    let listener = tokio::net::TcpListener::bind("127.0.0.1:3000").await.unwrap();
    tracing::info!("Listening on http://127.0.0.1:3000");
    axum::serve(listener, app).await.unwrap();
}

async fn home(State(state): State<Arc<AppState>>) -> Response {
    let route = "/";
    let render_mode = state
        .render_modes
        .get(route)
        .copied()
        .unwrap_or(RenderMode::Phase1ClientMount);
    let ir_module = state.ir_modules.get(route);

    // Phase 2 needs BOTH the module and its slot data: `render_page` falls
    // back to Phase 1 when either is None, which is how an SSR build silently
    // degrades to a client-mount shell. Start from the IR's own defaults here;
    // to server-render real data, replace this with
    // `SlotData::from_json(&serde_json::to_string(&data)?, module)` — the JSON
    // keys are the slot names in the emitted `.ir`.
    let slots = ir_module.map(|module| SlotData::new_from_defaults(&module.slots));

    let page = render_page(&PageConfig {
        title: "Home",
        route_pattern: route,
        manifest: &state.manifest,
        config_script: None,
        // Prefer config_json over config_script for anything derived from user
        // input: serde_json escapes every < , so it cannot break out of the script.
        config_json: None,
        body_class: None,
        personality_css: None,
        body_prefix: None,
        render_mode,
        ir_module,
        slots: slots.as_ref(),
    });
    // The CSP header carries the per-request nonce generated by render_page,
    // so it must come from the same call that produced the HTML.
    (
        [(header::HeaderName::from_static("content-security-policy"), page.csp)],
        Html(page.html),
    )
        .into_response()
}

async fn favicon() -> StatusCode {
    StatusCode::NO_CONTENT
}
