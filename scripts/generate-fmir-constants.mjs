#!/usr/bin/env node
// One wire-contract table, generated for the writer and reader. --check never writes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const table = JSON.parse(readFileSync(new URL('fmir-constants.json', root), 'utf8'));
const banner = '// Generated by scripts/generate-fmir-constants.mjs from fmir-constants.json. Do not edit.\n';
let ts = banner + `export const SIGNATURE = new Uint8Array(${JSON.stringify(table.signature)});\n`;
let rs = banner + `/// FMIR v3 signature.\npub const SIGNATURE: [u8; 8] = [${table.signature.join(', ')}];\n`;
for (const [group, values] of Object.entries(table)) {
  if (['signature', 'opcodes', 'reserved_opcodes'].includes(group)) continue;
  for (const [name, value] of Object.entries(values)) {
    const type = typeof value === 'string' ? '&str' : group === 'limits' || (group === 'layout' && name !== 'IR_VERSION') ? 'usize' : group === 'crc' ? 'u32' : ['layout', 'sections', 'flags'].includes(group) ? 'u16' : 'u8';
    ts += `export const ${name} = ${JSON.stringify(value)};\n`;
    rs += `/// Shared ${group.replaceAll('_', ' ')}: ${name}.\npub const ${name}: ${type} = ${JSON.stringify(value)};\n`;
  }
}
for (const op of table.opcodes) {
  ts += `export const ${op.name} = ${op.value};\n`;
  rs += `/// ${op.operands || 'No operands'}.\npub const ${op.name}: u8 = ${op.value};\n`;
}
rs += `/// Operand shapes for the twelve assigned opcodes.\npub const OPCODE_OPERANDS: &[(u8, &str)] = &[\n${table.opcodes.map(op => `    (${op.value}, ${JSON.stringify(op.operands)}),`).join("\n")}\n];\n`;
ts += `export const OPCODE_OPERANDS = ${JSON.stringify(Object.fromEntries(table.opcodes.map(op => [op.value, op.operands])), null, 2)} as const;\n`;
ts += `export const RESERVED_OPCODES: readonly number[] = ${JSON.stringify(table.reserved_opcodes)};\n`;
rs += `/// Reserved opcode bytes, never reassigned.\npub const RESERVED_OPCODES: [u8; ${table.reserved_opcodes.length}] = [${table.reserved_opcodes.join(', ')}];\n`;
const outputs = [['packages/compiler/src/fmir-constants.ts', ts], ['crates/forma-ir/src/fmir_constants.rs', rs]];
for (const [path, contents] of outputs) {
  const file = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== contents) throw new Error(`Generated FMIR constants are stale: ${fileURLToPath(file)}`);
  } else writeFileSync(file, contents);
}
