test('the pruned lock keeps what the crate reaches in the committed order, with checksums untouched and the Forma packages at the packed version', () => {
  const pruned = pruneCargoLock(lockText, 'forma-fixture-apps', '3.0.0-alpha.2');
  const names = [...pruned.matchAll(/^name = "([^"]+)"$/gm)].map(m => m[1]);
  assert.deepEqual(names, ['axum', 'forma-fixture-apps', 'forma-ir', 'forma-ir-derive', 'forma-server', 'serde']);
  assert(pruned.includes('checksum = "aaa"') && pruned.includes('checksum = "bbb"'), 'third-party checksums stay');
  assert(!pruned.includes('"ccc"') && !pruned.includes('forma-e2e-frame') && !pruned.includes('unused'), 'unreached packages go, including the other version of a shared name');
  for (const name of ['forma-ir', 'forma-ir-derive', 'forma-server']) assert.match(pruned, new RegExp(`name = "${name}"\\nversion = "3.0.0-alpha.2"`));
  assert.match(pruned, /name = "forma-fixture-apps"\nversion = "0.0.0"/, 'the crate keeps its own version');
  assert(pruned.startsWith('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]'));
  assert(pruned.endsWith('checksum = "bbb"\n'), 'cargo writes one final newline and compares text under --locked');
});

test('the pruned lock refuses a dependency the committed lock does not hold, an ambiguous one, and a Forma crate with a registry source', () => {
  assert.throws(() => pruneCargoLock(lockText.replace('name = "unused"\nversion = "1.0.0"', 'name = "other"\nversion = "1.0.0"').replace(' "axum",\n "forma-ir",\n "forma-server",', ' "axum",\n "missing",\n "forma-ir",\n "forma-server",'), 'forma-fixture-apps', '3.0.0'), /dependency missing is absent/);
  assert.throws(() => pruneCargoLock(lockText.replace('"serde 1.0.1"', '"serde"'), 'forma-fixture-apps', '3.0.0'), /dependency serde is ambiguous/);
  assert.throws(() => pruneCargoLock(lockText.replace('name = "forma-ir"\nversion = "3.0.0-dev"', 'name = "forma-ir"\nversion = "3.0.0-dev"\nsource = "registry+https://github.com/rust-lang/crates.io-index"'), 'forma-fixture-apps', '3.0.0'), /must hold the Forma crates as path packages/);
  assert.throws(() => pruneCargoLock(lockText, 'no-such-crate', '3.0.0'), /has no package no-such-crate/);
});

